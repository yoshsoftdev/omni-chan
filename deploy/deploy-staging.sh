#!/usr/bin/env bash
set -euo pipefail

# Staging deploy with Docker. Same script runs on your laptop and in GitHub Actions.
#
#   STAGING_HOST=deploy@<ip> ./deploy/deploy-staging.sh          # build + push + deploy
#   ./deploy/deploy-staging.sh build                             # build + push images only
#   STAGING_HOST=deploy@<ip> TAG=<sha> ./deploy/deploy-staging.sh deploy   # deploy/rollback an existing tag
#   ./deploy/deploy-staging.sh local                             # build + run on this machine (no registry, no VM)
#
# Env:
#   STAGING_HOST   user@host of the VM (deploy step)
#   TAG            image tag (default: short sha of this repo, "-dirty" if uncommitted changes)
#   REGISTRY       default ghcr.io/yoshsoftdev (run `docker login ghcr.io` first)
#   STAGING_DIR    default /srv/omni-chan on the VM
#   OBSERVABILITY  1 (default) also runs Grafana/Prometheus/Loki/Tempo; 0 to skip
#   NEXT_PUBLIC_WEBHOOK_URL  baked into the frontend bundle at build time
#   local mode: reads ./.env (from .env.staging.example), compose project "omni-staging";
#               POSTGRES_PUBLISH_PORT / REDIS_PUBLISH_PORT in .env if 5432/6379 are taken;
#               E2E=1 (default) adds docker-compose.e2e.yml (fake Meta Graph for ./deploy/e2e-staging.sh)
# Runbook: docs/runbooks/deploy-staging.md

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT_DIR}"

MODE="${1:-all}"
export REGISTRY="${REGISTRY:-ghcr.io/yoshsoftdev}"
STAGING_DIR="${STAGING_DIR:-/srv/omni-chan}"
OBSERVABILITY="${OBSERVABILITY:-1}"
if [[ -z "${TAG:-}" ]]; then
  TAG="$(git rev-parse --short HEAD)"
  [[ -z "$(git status --porcelain --ignore-submodules=none)" ]] || TAG="${TAG}-dirty"
fi
export TAG

FILES=(-f docker-compose.yml -f docker-compose.staging.yml)
[[ "${OBSERVABILITY}" == "1" ]] && FILES+=(-f docker-compose.observability.yml)

build() {
  echo "==> Building ${REGISTRY}/omni-chan-*:${TAG}"
  git submodule update --init --recursive
  # Runtime secrets are interpolated by compose even for `build`; they are not baked into images.
  export META_TOKEN_ENCRYPTION_KEY="${META_TOKEN_ENCRYPTION_KEY:-unused-at-build}"
  export DOCKER_DEFAULT_PLATFORM=linux/amd64 # VM is amd64
  docker compose -f docker-compose.yml -f docker-compose.staging.yml build
}

push() {
  docker compose -f docker-compose.yml -f docker-compose.staging.yml push \
    backend-service webhook-service storage-service frontend
}

deploy() {
  : "${STAGING_HOST:?set STAGING_HOST=user@host}"
  echo "==> Deploying ${TAG} to ${STAGING_HOST}:${STAGING_DIR}"
  # The VM only needs compose files + observability configs; images come from the registry.
  ssh "${STAGING_HOST}" "mkdir -p '${STAGING_DIR}/deploy'"
  rsync -az --delete docker-compose.yml docker-compose.staging.yml docker-compose.observability.yml \
    "${STAGING_HOST}:${STAGING_DIR}/"
  rsync -az --delete deploy/observability "${STAGING_HOST}:${STAGING_DIR}/deploy/"

  ssh "${STAGING_HOST}" bash -s -- "${STAGING_DIR}" "${TAG}" "${REGISTRY}" "${FILES[*]}" 1 < <(target_script)
  echo "==> Staging is on ${TAG}"
}

local_up() {
  echo "==> Running ${TAG} on this machine (compose project omni-staging)"
  [[ "${E2E:-1}" == "1" ]] && FILES+=(-f docker-compose.e2e.yml)
  # Compose project name keeps volumes apart from a dev `docker compose up` in this repo.
  env -u META_TOKEN_ENCRYPTION_KEY COMPOSE_PROJECT_NAME=omni-staging \
    bash -s -- "${ROOT_DIR}" "${TAG}" "${REGISTRY}" "${FILES[*]}" 0 < <(target_script)
}

# Runs on the target (VM over ssh, or this machine): args DIR TAG REGISTRY FILES PULL.
target_script() {
  cat <<'REMOTE'
set -euo pipefail
DIR="$1"; TAG="$2"; REGISTRY="$3"; read -r -a FILES <<<"$4"; PULL="$5"
cd "${DIR}"
[[ -f .env ]] || { echo "MISSING ${DIR}/.env — copy .env.staging.example there and fill it in"; exit 1; }
export TAG REGISTRY
# ./dc = docker compose pinned to the deployed tag and files, for debugging by hand (./dc logs -f backend-service).
cat > dc <<EOF
#!/usr/bin/env bash
# Generated by deploy-staging.sh — deployed tag ${TAG}
cd "\$(dirname "\$0")"
COMPOSE_PROJECT_NAME=${COMPOSE_PROJECT_NAME:-} TAG=${TAG} REGISTRY=${REGISTRY} exec docker compose ${FILES[*]} "\$@"
EOF
chmod +x dc
[[ "${PULL}" == "1" ]] && docker compose "${FILES[@]}" pull --quiet
docker compose "${FILES[@]}" up -d --no-build --remove-orphans --wait --wait-timeout 240 || {
  echo "==> Some services are not healthy:"
  docker compose "${FILES[@]}" ps
  echo "==> Logs: docker compose ${FILES[*]} logs --tail=100 <service>"
  exit 1
}
docker compose "${FILES[@]}" ps --format 'table {{.Service}}\t{{.Status}}'
[[ "${PULL}" == "1" ]] && docker image prune -f >/dev/null
true
REMOTE
}

case "${MODE}" in
  build) build && push ;;
  deploy) deploy ;;
  all) build && push && deploy ;;
  local) build && local_up ;;
  *) echo "usage: $0 [build|deploy|all|local]" >&2; exit 1 ;;
esac
